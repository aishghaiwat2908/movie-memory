"use client";

import { useEffect, useState } from "react";
import type { FactResponse } from "../../lib/fact-contract";

export function FactPanel() {
  const [attempt, setAttempt] = useState(0);
  const [fact, setFact] = useState<FactResponse | null>(null);

  useEffect(() => {
    const controller = new AbortController();

    async function loadFact() {
      try {
        const response = await fetch("/api/fact", { method: "POST", signal: controller.signal });
        const body: FactResponse = await response.json();
        if (!controller.signal.aborted) setFact(body);
      } catch {
        if (!controller.signal.aborted) setFact({ error: "Couldn’t load a movie fact. Try again." });
      }
    }

    void loadFact();
    return () => controller.abort();
  }, [attempt]);

  const error = fact && "error" in fact ? fact.error : null;

  return (
    <section className="panel fact-panel" aria-labelledby="fact-heading">
      <p className="eyebrow"><span className="accent-dot" /> Behind the scenes</p>
      <h2 id="fact-heading">Your movie fact</h2>
      <div aria-live="polite" aria-busy={!fact}>
        {!fact && <p className="muted mt-4">Looking for a movie fact…</p>}
        {error && <p className="error-note mt-4">{error}</p>}
        {fact && "text" in fact && (
          <>
            <p className="fact-text">{fact.text}</p>
            <p className="muted text-sm">
              {fact.source === "stale" ? "Saved fact · A new fact is temporarily unavailable." : "Generated by AI"}
            </p>
          </>
        )}
      </div>
      {(error || (fact && "source" in fact && fact.source === "stale")) && (
        <button className="button button-quiet mt-5" type="button" onClick={() => {
          setFact(null);
          setAttempt((value) => value + 1);
        }}>Try again</button>
      )}
    </section>
  );
}
